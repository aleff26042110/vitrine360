// Isolated browser storage. UI and real local file saving; no customer content is modified.
import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const base=process.env.VITRINE_TEST_URL || 'http://localhost:5188'
await mkdir('.tmp-ui/storefront-repair',{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true})
const context=await browser.newContext({viewport:{width:1440,height:1000}})
const page=await context.newPage(),errors=[]
page.on('pageerror',e=>errors.push(e.message))
try{
 await page.goto(base+'/minha-vitrine')
 await page.getByLabel('Nome da vitrine',{exact:true}).fill('Minha coleção nova')
 await page.getByLabel('Frase de apresentação',{exact:true}).fill('Detalhes que merecem outro olhar.')
 await page.getByRole('button',{name:'Aparência',exact:true}).click()
 for(const name of ['Editorial','Galeria','Showroom','Joalheria Luxo','Concessionária Premium','Jardim Botânico','Estúdio Nórdico','Art Déco','Concreto Brutal']){
   await page.locator('.storefront-template-option').filter({has:page.getByText(name,{exact:true})}).click()
   await page.getByRole('button',{name:'Aplicar paleta Contemporânea'}).click()
   const bg=await page.locator('.storefront-view').evaluate(el=>getComputedStyle(el).backgroundColor)
   assert.equal(bg,'rgb(255, 255, 255)',name+' respects chosen background')
   for(const width of [390,1440]){
     await page.setViewportSize({width,height:1000})
     assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),name+' page overflow')
     assert.ok(await page.locator('.storefront-view').evaluate(el=>el.scrollWidth<=el.clientWidth+1),name+' preview overflow')
   }
   await page.getByRole('button',{name:'Aplicar paleta Noturna'}).click()
   assert.equal(await page.locator('.storefront-view').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(23, 29, 36)')
 }
 await page.getByLabel('Mostrar preços',{exact:true}).uncheck()
 await page.getByLabel('Mostrar descrições dos produtos',{exact:true}).uncheck()
 await page.getByLabel('Enquadramento das fotos').selectOption('contain')
 assert.equal(await page.locator('.sf-item-text>strong').count(),0)
 assert.equal(await page.locator('.sf-item-text>p').count(),0)
 assert.equal(await page.locator('.sf-item-image>img').first().evaluate(el=>getComputedStyle(el).objectFit),'contain')
 await page.getByRole('button',{name:'Itens 360°',exact:true}).click()
 await page.getByRole('link',{name:'Criar objeto 360°',exact:true}).click()
 await page.waitForURL(/\/spin\/.+\/edit\?from=storefront/)
 assert.equal(await page.locator('.creation-back').getAttribute('href'),'/minha-vitrine?tab=items')
 await page.getByLabel('Nome do projeto').fill('Produto da nova coleção')
 const png=Buffer.from(await page.evaluate(()=>{const c=document.createElement('canvas');c.width=200;c.height=200;const ctx=c.getContext('2d');ctx.fillStyle='#386550';ctx.fillRect(0,0,200,200);return c.toDataURL().split(',')[1]}),'base64')
 await page.locator('input[type=file]').first().setInputFiles([{name:'01.png',mimeType:'image/png',buffer:png},{name:'02.png',mimeType:'image/png',buffer:png}])
 await page.getByRole('button',{name:'Adicionar à vitrine',exact:true}).click()
 await page.waitForURL(/minha-vitrine/)
 await page.locator('.storefront-inventory-item input:checked').waitFor()
 assert.equal(await page.locator('.storefront-inventory-item input:checked').count(),1)
 await page.getByRole('button',{name:'Identidade',exact:true}).click()
 assert.equal(await page.getByLabel('Nome da vitrine',{exact:true}).inputValue(),'Minha coleção nova')
 await page.reload()
 await page.getByRole('button',{name:'Identidade',exact:true}).click()
 assert.equal(await page.getByLabel('Nome da vitrine',{exact:true}).inputValue(),'Minha coleção nova')
 await page.getByRole('button',{name:'Itens 360°',exact:true}).click()
 await page.getByRole('button',{name:'Remover todos da vitrine',exact:true}).click()
 assert.equal(await page.locator('.storefront-inventory-item input:checked').count(),0)
 assert.equal(await page.locator('.sf-item').count(),0)
 assert.equal(await page.locator('.storefront-inventory-item').count(),1,'Library is preserved')
 await page.getByRole('button',{name:'Identidade',exact:true}).click()
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('button',{name:'Limpar dados da vitrine',exact:true}).click()
 assert.equal(await page.getByLabel('Frase de apresentação',{exact:true}).inputValue(),'')
 await page.getByRole('button',{name:'Desfazer limpeza',exact:true}).click()
 assert.equal(await page.getByLabel('Nome da vitrine',{exact:true}).inputValue(),'Minha coleção nova')
 await page.getByLabel('Nome da vitrine',{exact:true}).fill('')
 await page.getByRole('button',{name:'Salvar rascunho',exact:true}).click()
 await page.getByRole('alert').filter({hasText:'Informe o nome'}).waitFor()
 await page.getByLabel('Nome da vitrine',{exact:true}).fill('Novos dados finais')
 await page.getByRole('button',{name:'Salvar rascunho',exact:true}).click()
 await page.getByRole('status').filter({hasText:'Rascunho salvo neste navegador'}).waitFor()
 assert.deepEqual(errors,[])
 console.log('PASS: nine themes, custom light/dark colors, responsive layouts, display controls, draft recovery, upload/add/return, remove/reset/undo and validation')
}finally{await context.close();await browser.close()}
