    async function record(width, height, name) {
      const canvas = document.createElement('canvas'); canvas.width = width; canvas.height = height
      const ctx = canvas.getContext('2d'), stream = canvas.captureStream(12)
      const recorder = new MediaRecorder(stream, { mimeType: 'video/webm' }), chunks = []
      recorder.ondataavailable = event => chunks.push(event.data)
      const stopped = new Promise(resolve => { recorder.onstop = resolve })
      let step = 0
      const draw = () => { ctx.fillStyle = '#1a8977'; ctx.fillRect(0,0,width,height); ctx.fillStyle='#f4bb42'; ctx.fillRect(width*.25,0,width*.25,height); ctx.fillStyle='#d5e9f4'; ctx.fillRect(width*.5,0,width*.25,height); ctx.fillStyle='#b75150'; ctx.fillRect(width*.75,0,width*.25,height); ctx.fillStyle='white';ctx.font='30px sans-serif';ctx.fillText(name+' '+step++,width*.3,height*.5) }
      draw(); recorder.start(); const interval = setInterval(draw,80)
      await new Promise(resolve => setTimeout(resolve,2000)); recorder.stop();await stopped;clearInterval(interval);stream.getTracks().forEach(track=>track.stop())
      return new File(chunks,name+'.webm',{type:'video/webm'})
    }
    const files = new DataTransfer(); files.items.add(await record(800,400,'panoramico'));files.items.add(await record(640,360,'normal'))
